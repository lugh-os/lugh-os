#!/usr/bin/env bash
# Publish out/debs/*.deb as a signed apt repository in out/repo/ (ADR-003).
#
#   scripts/repo-publish.sh          # what `make repo` runs
#
# Result (consumed by the ISO build, served as
# `deb http://127.0.0.1:8099 trixie main`):
#   out/repo/dists/trixie/{InRelease,Release,Release.gpg}
#   out/repo/pool/main/...
#   out/repo/lugh.asc                 public key that signed the metadata
#
# Signing key:
#   LUGH_REPO_GPG_KEY=<ASCII-armored secret (sub)key>   CI / release signing
#   LUGH_REPO_GPG_PASSPHRASE=<passphrase>               optional, if the key has one
#   (unset)  a throwaway dev key is generated once into out/dev-key/ and used,
#            with a loud warning. Never ship a repo signed with it.
#
# aptly runs inside the build container (scripts/lib/container.sh) with
# packaging/repo/aptly.conf; its database lives in out/aptly/.
# Set LUGH_NO_CONTAINER=1 to run directly when already inside the build
# container with the checkout at /src (aptly.conf uses /src/out/... paths).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

APTLY_REPO="lugh-trixie"
DISTRIBUTION="trixie"
COMPONENT="main"
ARCHITECTURES="amd64,all"
ENDPOINT="filesystem:lugh:."
DEV_KEY_UID="Lugh DEV KEY - NOT FOR RELEASE <dev-key@lugh.invalid>"

log() { printf '\033[1m==> %s\033[0m\n' "$*" >&2; }
die() { printf '\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

loud_dev_key_warning() {
  local line='!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!'
  {
    printf '\033[1;33m%s\n' "$line"
    printf '!!  LUGH_REPO_GPG_KEY is not set: signing out/repo/ with the THROWAWAY\n'
    printf '!!  DEV KEY "Lugh DEV KEY - NOT FOR RELEASE" (cached in out/dev-key/).\n'
    printf '!!  This repo and any ISO built from it are for local testing ONLY.\n'
    printf '!!  NEVER publish them. See docs/dev/signing.md.\n'
    printf '%s\033[0m\n' "$line"
  } >&2
}

# ---------------------------------------------------------------------------
# Inside the build environment: the actual work.
# ---------------------------------------------------------------------------
in_build_env() {
  local src="$REPO_ROOT"
  local out="$src/out"
  local conf="$src/packaging/repo/aptly.conf"

  command -v aptly >/dev/null || die "aptly not found (run in the build container)"
  command -v gpg >/dev/null || die "gpg not found"

  shopt -s nullglob
  local debs=("$out"/debs/*.deb)
  shopt -u nullglob
  ((${#debs[@]})) || die "no .deb files in out/debs/ (run scripts/build-debs.sh first)"

  # Throwaway GNUPGHOME for this run only; a short path keeps the agent socket
  # path under the unix socket length limit.
  local gnupghome
  gnupghome="$(mktemp -d /tmp/lugh-gpg.XXXXXX)"
  export GNUPGHOME="$gnupghome"
  chmod 700 "$GNUPGHOME"
  # shellcheck disable=SC2064
  trap "gpgconf --kill all >/dev/null 2>&1 || true; rm -rf '$gnupghome'" EXIT

  local key_source dev_key=0
  if [[ -n "${LUGH_REPO_GPG_KEY:-}" ]]; then
    key_source="$GNUPGHOME/import.asc"
    (umask 077 && printf '%s\n' "$LUGH_REPO_GPG_KEY" >"$key_source")
    log "Signing with LUGH_REPO_GPG_KEY"
  else
    dev_key=1
    loud_dev_key_warning
    local dev_dir="$out/dev-key"
    if [[ ! -s "$dev_dir/secret.asc" ]]; then
      log "Generating the throwaway dev key into out/dev-key/ (once)"
      mkdir -p "$dev_dir"
      chmod 700 "$dev_dir"
      # Same shape as the real key (docs/dev/signing.md): an Ed25519 primary
      # that only certifies, plus an Ed25519 signing subkey. No passphrase.
      gpg --batch --quiet --pinentry-mode loopback --passphrase '' \
        --quick-generate-key "$DEV_KEY_UID" ed25519 cert never
      local dev_fpr
      dev_fpr="$(gpg --batch --with-colons --list-secret-keys "$DEV_KEY_UID" |
        awk -F: '$1=="fpr"{print $10; exit}')"
      gpg --batch --quiet --pinentry-mode loopback --passphrase '' \
        --quick-add-key "$dev_fpr" ed25519 sign never
      (umask 077 && gpg --batch --armor --export-secret-keys "$dev_fpr" >"$dev_dir/secret.asc")
      gpg --batch --armor --export "$dev_fpr" >"$dev_dir/public.asc"
      printf '%s\n' "$dev_fpr" >"$dev_dir/fingerprint"
      cat >"$dev_dir/README" <<'README'
Throwaway Lugh DEV KEY - NOT FOR RELEASE.
Generated by scripts/repo-publish.sh for local builds. Delete this directory to
rotate it. Never use it to sign anything that leaves this machine.
README
      # Start from an empty keyring again so dev and CI paths are identical.
      gpgconf --kill all >/dev/null 2>&1 || true
      rm -rf "${GNUPGHOME:?}"/*
    fi
    key_source="$dev_dir/secret.asc"
  fi

  gpg --batch --import "$key_source" 2>/dev/null ||
    die "could not import the signing key (is LUGH_REPO_GPG_KEY an ASCII-armored secret key?)"

  # Primary fingerprint; gpg picks the newest valid signing subkey whose
  # secret part is present (the primary may be a stub, sec#, in CI).
  local fpr
  fpr="$(gpg --batch --with-colons --list-secret-keys | awk -F: '$1=="fpr"{print $10; exit}')"
  [[ -n "$fpr" ]] || die "no secret key found after import"
  local can_sign
  can_sign="$(gpg --batch --with-colons --list-secret-keys "$fpr" |
    awk -F: '($1=="sec"||$1=="ssb") && $12 ~ /[sS]/ && $2 !~ /[erd]/ {print "yes"; exit}')"
  [[ "$can_sign" == yes ]] || die "the signing key $fpr has no usable (unexpired, unrevoked) signing key"
  gpg --batch --yes --quick-set-ownertrust "$fpr" ultimate 2>/dev/null ||
    echo "$fpr:6:" | gpg --batch --import-ownertrust 2>/dev/null

  local passphrase_args=()
  if ((dev_key == 0)) && [[ -n "${LUGH_REPO_GPG_PASSPHRASE:-}" ]]; then
    (umask 077 && printf '%s' "$LUGH_REPO_GPG_PASSPHRASE" >"$GNUPGHOME/passphrase")
    passphrase_args=(-passphrase-file="$GNUPGHOME/passphrase")
  fi

  local aptly=(aptly -config="$conf")
  mkdir -p "$out/aptly"

  if ! "${aptly[@]}" repo show "$APTLY_REPO" >/dev/null 2>&1; then
    log "Creating aptly repo $APTLY_REPO"
    "${aptly[@]}" repo create \
      -comment="Lugh packages for Debian 13 trixie" \
      -distribution="$DISTRIBUTION" -component="$COMPONENT" \
      "$APTLY_REPO"
  fi

  # The local repo mirrors out/debs/ exactly: drop what an earlier run added
  # (renamed or removed packages must not leak into the ISO), then add the
  # current set. -force-replace: a rebuilt package with the same version
  # replaces the old one. Channel history (dev/beta/stable) is kept with aptly
  # snapshots in a later phase, not in this repo.
  "${aptly[@]}" repo remove "$APTLY_REPO" 'Name (~ .)' >/dev/null
  log "Adding ${#debs[@]} package(s) from out/debs/"
  "${aptly[@]}" repo add -force-replace "$APTLY_REPO" "${debs[@]}"

  # Publish from scratch each time: out/repo/ always matches the aptly repo and
  # the current key.
  if "${aptly[@]}" publish list -raw 2>/dev/null | grep -qE "(^| )$DISTRIBUTION\$"; then
    "${aptly[@]}" publish drop -force-drop "$DISTRIBUTION" "$ENDPOINT" >/dev/null
  fi
  rm -rf "$out/repo"
  mkdir -p "$out/repo"
  "${aptly[@]}" db cleanup >/dev/null

  log "Publishing $DISTRIBUTION/$COMPONENT ($ARCHITECTURES) to out/repo/"
  "${aptly[@]}" publish repo \
    -batch \
    -gpg-key="$fpr" \
    "${passphrase_args[@]}" \
    -distribution="$DISTRIBUTION" \
    -component="$COMPONENT" \
    -architectures="$ARCHITECTURES" \
    -origin="Lugh" \
    -label="Lugh" \
    "$APTLY_REPO" "$ENDPOINT"

  gpg --batch --armor --export-options export-minimal --export "$fpr" >"$out/repo/lugh.asc"

  # Self-check: the published metadata verifies against the exported key.
  local vhome
  vhome="$(mktemp -d /tmp/lugh-verify.XXXXXX)"
  gpg --homedir "$vhome" --batch --quiet --import "$out/repo/lugh.asc" 2>/dev/null
  gpg --homedir "$vhome" --batch --quiet --verify "$out/repo/dists/$DISTRIBUTION/InRelease" 2>/dev/null ||
    die "out/repo/dists/$DISTRIBUTION/InRelease does not verify against out/repo/lugh.asc"
  gpgconf --homedir "$vhome" --kill all >/dev/null 2>&1 || true
  rm -rf "$vhome"

  "${aptly[@]}" repo show -with-packages "$APTLY_REPO" | sed -n '/^Packages:/,$p'
  log "out/repo/ published and signed by $fpr"
  ((dev_key == 0)) || loud_dev_key_warning
}

# ---------------------------------------------------------------------------
# On the host: re-run this script in the build container. run_in_build_env
# passes every LUGH_* variable through, so the key never touches the checkout.
# ---------------------------------------------------------------------------
main() {
  if [[ "${1:-}" == "--in-build-env" || "${LUGH_NO_CONTAINER:-0}" == 1 ]]; then
    in_build_env
    return
  fi
  # shellcheck source=scripts/lib/container.sh
  source "$REPO_ROOT/scripts/lib/container.sh"
  ensure_build_image
  run_in_build_env -- /src/scripts/repo-publish.sh --in-build-env
}

main "$@"
