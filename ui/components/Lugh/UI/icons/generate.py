#!/usr/bin/env python3
"""Regenerate the vendored Lucide icon font and IconNames.qml.

    ui/components/Lugh/UI/icons/generate.py                 # npm pack lucide-static (latest)
    ui/components/Lugh/UI/icons/generate.py --version 1.71.0
    ui/components/Lugh/UI/icons/generate.py --pkg /path/to/extracted/package

Writes:
    ui/components/fonts/lucide.ttf
    ui/components/LICENSES/lucide-ISC.txt
    ui/components/Lugh/UI/icons/IconNames.qml
"""
import argparse
import json
import pathlib
import shutil
import subprocess
import tarfile
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
COMPONENTS = HERE.parents[2]  # ui/components
FONT_OUT = COMPONENTS / "fonts" / "lucide.ttf"
LICENSE_OUT = COMPONENTS / "LICENSES" / "lucide-ISC.txt"
QML_OUT = HERE / "IconNames.qml"

HEADER = """\
// GENERATED by generate.py from lucide-static {version} — do not edit by hand.
// Lucide icon font (ISC, see ui/components/LICENSES/lucide-ISC.txt): {count} icons.
//
//   Text { font.family: IconNames.fontFamily; text: IconNames.glyph("wifi") }
//   (or simply: Icon { name: "wifi" })
pragma Singleton
import QtQuick

QtObject {
    id: root

    // Family name of the loaded font ("lucide").
    readonly property string fontFamily: _loader.status === FontLoader.Ready ? _loader.name : "lucide"
    readonly property bool ready: _loader.status === FontLoader.Ready
    readonly property int count: {count}
    readonly property string version: "{version}"

    // The glyph character for a Lucide kebab-case name, or "" if unknown.
    function glyph(name) {
        const cp = _map[name];
        return cp === undefined ? "" : String.fromCharCode(cp);
    }
    function has(name) { return _map[name] !== undefined; }

    // Icon calls this for an unknown name; each name warns once per process.
    function warnUnknown(name) {
        if (_warned[name]) return;
        _warned[name] = true;
        console.warn('Lugh.UI Icon: unknown Lucide icon name "' + name + '"');
    }
    property var _warned: ({})

    readonly property FontLoader _loader: FontLoader {
        source: Qt.resolvedUrl("../../../fonts/lucide.ttf")
    }

    // name -> codepoint (all in the BMP private-use area).
    readonly property var _map: ({
"""

FOOTER = """\
    })
}
"""


def fetch(version):
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="lucide-static-"))
    spec = "lucide-static" + (f"@{version}" if version else "")
    subprocess.run(["npm", "pack", spec, "--silent"], cwd=tmp, check=True)
    tgz = next(tmp.glob("lucide-static-*.tgz"))
    with tarfile.open(tgz) as tf:
        tf.extractall(tmp, filter="data")
    return tmp / "package"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pkg", type=pathlib.Path, help="extracted lucide-static package dir")
    ap.add_argument("--version", default="", help="lucide-static version for npm pack")
    args = ap.parse_args()
    pkg = args.pkg or fetch(args.version)

    version = json.loads((pkg / "package.json").read_text())["version"]
    cps = json.loads((pkg / "font" / "codepoints.json").read_text())
    for name, cp in cps.items():
        if not (0xE000 <= cp <= 0xF8FF):  # String.fromCharCode needs BMP
            raise SystemExit(f"{name}: codepoint {cp:#x} outside BMP PUA")

    FONT_OUT.parent.mkdir(parents=True, exist_ok=True)
    LICENSE_OUT.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(pkg / "font" / "lucide.ttf", FONT_OUT)
    shutil.copyfile(pkg / "LICENSE", LICENSE_OUT)

    lines = [f'        "{n}": {cps[n]}' for n in sorted(cps)]
    QML_OUT.write_text(HEADER.replace("{version}", version).replace("{count}", str(len(cps)))
                       + ",\n".join(lines) + "\n" + FOOTER)
    print(f"lucide-static {version}: {len(cps)} icons -> {QML_OUT}")


if __name__ == "__main__":
    main()
